import {execFileSync} from 'node:child_process';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {buildGraph} from './extract.mjs';
import {scanDeclarations} from './city-v2-inventory.mjs';
import {RESULT_REVISION,PILOT_ROOTS,PREFIXES,normalizePilot,summarizePilot} from './elaborated-pilot.mjs';
const [physArg,resultArg,outArg]=process.argv.slice(2);
if(!outArg)throw Error('Usage: node scripts/run-elaborated-pilot.mjs <physlib> <result-graph> <output-dir>');
const phys=path.resolve(physArg),result=path.resolve(resultArg),out=path.resolve(outArg);
const git=(cwd,...args)=>execFileSync('git',['-C',cwd,...args],{encoding:'utf8'}).trim();
const clean=cwd=>{if(git(cwd,'status','--porcelain'))throw Error('Dirty source '+cwd);return git(cwd,'rev-parse','HEAD');};
const physlibRevision=clean(phys),extractorRevision=clean(result);
if(extractorRevision!==RESULT_REVISION)throw Error('Unsupported result-graph checkout');
const graph=await buildGraph(phys),toolchain=graph.source.toolchain;
const manifest=JSON.parse(await readFile(path.join(phys,'lake-manifest.json'),'utf8')),mathlibRevision=manifest.packages.find(p=>p.name==='mathlib')?.rev;
if(!mathlibRevision)throw Error('Mathlib pin missing');
const mathlib=path.join(phys,'.lake/packages/mathlib');
if(clean(mathlib)!==mathlibRevision)throw Error('Mathlib checkout mismatch');
await mkdir(out,{recursive:true});
const timings={};
function timed(label,command,args,cwd){const start=Date.now();execFileSync('/usr/bin/time',['-v','-o',path.join(out,label+'.time.txt'),command,...args],{cwd,stdio:'inherit',env:{...process.env,LEAN_ABORT_ON_PANIC:'1'}});timings[label]=(Date.now()-start)/1000;}
timed('extractor-build','elan',['run',toolchain,'lake','build'],result);
timed('physlib-build','lake',['build',...PILOT_ROOTS.map(m=>'+'+m)],phys);
const rawPath=path.join(out,'raw.json'),flags=['--private','--auto'];
timed('extract','lake',['env',path.join(result,'.lake/build/bin/result-graph'),...PILOT_ROOTS.flatMap(m=>['--root',m]),...PREFIXES.flatMap(m=>['--include-prefix',m]),...flags,'--json',rawPath,'--stats'],phys);
if(clean(phys)!==physlibRevision||clean(result)!==extractorRevision||clean(mathlib)!==mathlibRevision)throw Error('Source changed during run');
const rawBytes=await readFile(rawPath),rawSha256=createHash('sha256').update(rawBytes).digest('hex');
const provenance={physlibRevision,mathlibRevision,toolchain,extractorRevision,rawSha256,roots:PILOT_ROOTS,includedPrefixes:PREFIXES,flags};
const snapshot=normalizePilot(JSON.parse(rawBytes),graph,provenance);
const declarations=[];for(const m of graph.modules.filter(m=>PILOT_ROOTS.includes(m.id)))declarations.push(...scanDeclarations(m,await readFile(path.join(phys,m.path),'utf8')));
const report={...summarizePilot(snapshot,{declarations}),timingsSeconds:timings,rawBytes:rawBytes.length};
await writeFile(path.join(out,'provenance.json'),JSON.stringify(provenance,null,2));
await writeFile(path.join(out,'snapshot.json'),JSON.stringify(snapshot));
await writeFile(path.join(out,'report.json'),JSON.stringify(report,null,2));
console.log('ELABORATED PILOT SUMMARY',JSON.stringify({...report,roots:report.roots.map(({matches,...x})=>x)}));
